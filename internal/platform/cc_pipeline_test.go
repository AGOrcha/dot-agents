func emitCC(t *testing.T, spec PipelineSpec) []PipelineArtifact {
	t.Helper()
	arts, err := ccPipelineProjector{}.Emit(spec)
	if err != nil {
		t.Fatalf("cc emit: %v", err)
	}
	return arts
}

// extractManifestJSON pulls the `export const MANIFEST = {…}` payload out of an
// emitted `.mjs` so a test can parse the generated stage table directly.
func extractManifestJSON(t *testing.T, content string) string {
	t.Helper()
	const prefix = "export const MANIFEST = "
	i := strings.Index(content, prefix)
	if i < 0 {
		t.Fatal("emitted mjs has no MANIFEST block")
	}
	rest := content[i+len(prefix):]
	end := strings.Index(rest, "\n// ======================= END GENERATED MANIFEST")
	if end < 0 {
		t.Fatal("emitted mjs manifest has no END banner")
	}
	return rest[:end]
}

func parseCCManifest(t *testing.T, content string) ccManifest {
	t.Helper()
	var m ccManifest
	if err := json.Unmarshal([]byte(extractManifestJSON(t, content)), &m); err != nil {
		t.Fatalf("manifest JSON does not parse: %v", err)
	}
	return m
}

