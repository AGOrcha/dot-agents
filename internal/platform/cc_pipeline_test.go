// assertCCSkeletonManifest checks the full per-task stage table (7 verify + 4
// routine + cross-family) with the resolved model routes and caps intact.
func assertCCSkeletonManifest(t *testing.T, m ccManifest) {
	t.Helper()
	if m.TargetCount != pipelineTargetCount {
		t.Fatalf("target_count = %d, want %d", m.TargetCount, pipelineTargetCount)
	}
	if m.Executor.Model != "claude-opus-4-8" || m.Executor.Family != "claude" {
		t.Fatalf("executor route = %+v", m.Executor)
	}
	if len(m.Verifiers) != maxPipelineVerifiers {
		t.Fatalf("verifiers = %d, want %d", len(m.Verifiers), maxPipelineVerifiers)
	}
	for i, v := range m.Verifiers {
		if v.Model != "claude-opus-4-8" || v.Family != "claude" {
			t.Fatalf("verifier[%d] route = %+v", i, v)
		}
	}
	if len(m.RoutineLenses) != maxPipelineRoutineLenses {
		t.Fatalf("routine lenses = %d, want %d", len(m.RoutineLenses), maxPipelineRoutineLenses)
	}
	assertCCCrossFamily(t, m)
	if m.Caps.MaxVerifiers != maxPipelineVerifiers || m.Caps.MaxRoutineLenses != maxPipelineRoutineLenses {
		t.Fatalf("caps = %+v", m.Caps)
	}
}

// assertCCCrossFamily checks the manifest cross-family binding (RULE-7): the
// NAMED slug, the resolved route, and a family that differs from the executor.
func assertCCCrossFamily(t *testing.T, m ccManifest) {
	t.Helper()
	if m.CrossFamily == nil {
		t.Fatal("skeleton must have a cross-family gate")
	}
	if m.CrossFamily.Slug != crossFamilyLensSlug {
		t.Fatalf("cross-family slug = %q, want %q", m.CrossFamily.Slug, crossFamilyLensSlug)
	}
	if m.CrossFamily.Model != "gpt-5.4" || m.CrossFamily.Family != "gpt" {
		t.Fatalf("cross-family route = %+v", m.CrossFamily)
	}
	if m.CrossFamily.Family == m.Executor.Family {
		t.Fatal("cross-family family must differ from executor (RULE-7)")
	}
	if m.CrossFamilySlug != crossFamilyLensSlug {
		t.Fatalf("manifest crossFamilySlug = %q", m.CrossFamilySlug)
	}
}

// assertCCReconcileManifest checks the app_type-agnostic reconcile artifact:
// executor route only, workspace, and the stamped config digest.
func assertCCReconcileManifest(t *testing.T, reconcile string) {
	t.Helper()
	var rm ccReconcileManifest
	if err := json.Unmarshal([]byte(extractManifestJSON(t, reconcile)), &rm); err != nil {
		t.Fatalf("reconcile manifest JSON does not parse: %v", err)
	}
	if rm.Model != "claude-opus-4-8" || rm.Family != "claude" || rm.Workspace != "/repo" {
		t.Fatalf("reconcile manifest = %+v", rm)
	}
	if rm.ConfigDigest != skeletonSpec("/repo").Digest() {
		t.Fatalf("reconcile digest = %q, want %q", rm.ConfigDigest, skeletonSpec("/repo").Digest())
	}
}

