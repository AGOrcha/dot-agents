// stripTrailingReturn removes the single harness-only top-level `return {…}` so
// the emitted body parses as a real ES module (the ultracode-wave-engine test
// idiom). Node rejects a top-level return in a `.mjs`, so this must run before
// any `node --check` or import.
var ccTrailingReturn = regexp.MustCompile(`(?s)\nreturn \{.*\}\s*$`)

func stripTrailingReturn(content string) string {
	return ccTrailingReturn.ReplaceAllString(content, "\n")
}

// harnessEvalForm rewrites an emitted artifact into the form the Claude-Code
// workflow harness actually evaluates: the harness injects agent/parallel/... as
// globals, wraps the file body in an (async) function scope, and consumes the
// authored trailing top-level `return` as the run result (the ultracode-wave-engine
// idiom). A raw ES module rejects that top-level return and a bare function body
// rejects the module-level exports, so NEITHER raw form is node --check-clean by
// design. Mirroring the harness — strip the module-only `export` keywords and wrap
// the whole body (INCLUDING the trailing return) in an async function — yields the
// exact bytes the harness runs in a scope where they are legal, so node --check
// validates the real artifact, return and all.
func harnessEvalForm(content string) string {
	body := strings.ReplaceAll(content, "\nexport ", "\n")
	return "async function __wf__(args) {\n" + body + "\n}\n"
}

// TestCCEmittedMjsHarnessFormPassesNodeCheck validates each emitted artifact IN
// THE FORM THE HARNESS EVALUATES IT, not raw. Decision (documented here so no
// later reader mistakes the intent): the artifact deliberately follows the
// authored ultracode-wave-engine top-level-return idiom, so a RAW `node --check`
// fails by design and no artifact/header claims raw node-check validity. We
// instead node --check the harness-eval form (harnessEvalForm), which exercises
// the real artifact bytes — including the trailing return — in the injected
// function scope the harness runs them in. Skips when node is unavailable.
func TestCCEmittedMjsHarnessFormPassesNodeCheck(t *testing.T) {
	node := ccNode(t)
	dir := t.TempDir()
	for i, art := range emitCC(t, skeletonSpec("/repo")) {
		// The raw artifact is NOT node --check-clean (top-level return idiom);
		// validate the harness-eval form the CC harness actually evaluates.
		path := filepath.Join(dir, art.Name)
		if err := os.WriteFile(path, []byte(harnessEvalForm(art.Content)), 0o644); err != nil {
			t.Fatal(err)
		}
		if out, err := exec.Command(node, "--check", path).CombinedOutput(); err != nil {
			t.Fatalf("node --check (harness-eval form) failed for artifact %d (%s): %v\n%s", i, art.Name, err, out)
		}
	}
}

// TestCCRunnerExecutesUnderNode imports the stripped runner and exercises the
// stable helpers: stageSequence must materialize the exact stage ordering, and
// assertCrossFamily must throw on a same-family or mis-slugged cross lens
// (RULE-7 refusal on the JS side). Skips when node is unavailable.
func TestCCRunnerExecutesUnderNode(t *testing.T) {
	node := ccNode(t)
	dir, _ := ccStrippedModule(t)
	driver := filepath.Join(dir, "driver.mjs")
	driverSrc := "import { MANIFEST, stageSequence, assertCrossFamily } from './module.mjs'\n" +
		"const kinds = stageSequence(MANIFEST).map((s) => s.kind)\n" +
		"const caught = (fn) => { try { fn(); return false } catch { return true } }\n" +
		"const rule7Same = caught(() => assertCrossFamily({ crossFamilySlug: 'cross-harness-adversarial', executor: { family: 'claude' }, crossFamily: { slug: 'cross-harness-adversarial', family: 'claude' } }))\n" +
		"const rule7Slug = caught(() => assertCrossFamily({ crossFamilySlug: 'cross-harness-adversarial', executor: { family: 'claude' }, crossFamily: { slug: 'wrong', family: 'gpt' } }))\n" +
		"process.stdout.write(JSON.stringify({ kinds, rule7Same, rule7Slug }))\n"
	if err := os.WriteFile(driver, []byte(driverSrc), 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command(node, driver).CombinedOutput()
	if err != nil {
		t.Fatalf("node driver failed: %v\n%s", err, out)
	}
	var res struct {
		Kinds     []string `json:"kinds"`
		Rule7Same bool     `json:"rule7Same"`
		Rule7Slug bool     `json:"rule7Slug"`
	}
	if err := json.Unmarshal(out, &res); err != nil {
		t.Fatalf("driver output does not parse: %v\n%s", err, out)
	}
	// profile_resolve + executor + 7 verify + 4 routine + cross_family + gate.
	want := []string{"profile_resolve", "executor", "verify", "verify", "verify", "verify", "verify", "verify", "verify", "routine", "routine", "routine", "routine", "cross_family", "gate"}
	if strings.Join(res.Kinds, ",") != strings.Join(want, ",") {
		t.Fatalf("stage sequence = %v, want %v", res.Kinds, want)
	}
	if !res.Rule7Same {
		t.Fatal("assertCrossFamily must throw on a same-family cross lens (RULE-7)")
	}
	if !res.Rule7Slug {
		t.Fatal("assertCrossFamily must throw on a mis-slugged cross lens")
	}
}

// ccNode resolves the node binary or skips: every CC runner exercise validates
// the emitted JS against the real interpreter, never a mock of node itself.
func ccNode(t *testing.T) string {
	t.Helper()
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node not available; skipping runner exercise")
	}
	return node
}

// ccStrippedModule writes the emitted skeleton pipeline as an importable ES
// module (the harness-only trailing return removed) into a fresh temp dir and
// returns the dir plus the module path.
func ccStrippedModule(t *testing.T) (string, string) {
	t.Helper()
	dir := t.TempDir()
	module := filepath.Join(dir, "module.mjs")
	body := stripTrailingReturn(emitCC(t, skeletonSpec("/repo"))[0].Content)
	if err := os.WriteFile(module, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir, module
}

// ccMockResult is the driver-visible state a mock CC runner surfaces: the ordered
// agent labels that actually launched and the evidence gate's rendered prompt.
type ccMockResult struct {
	Labels     []string `json:"labels"`
	GatePrompt string   `json:"gatePrompt"`
}

// ccMockRun evaluates the emitted pipeline in the harness-eval form with mocked
// agent/parallel/phase/log globals, so the real runner-body gating logic runs
// under node. agentBody is the mock agent's return statement(s); the mock records
// every launched stage's label so the test can assert which stages were skipped.
func ccMockRun(t *testing.T, agentBody string) ccMockResult {
	t.Helper()
	node := ccNode(t)
	dir := t.TempDir()
	content := emitCC(t, skeletonSpec("/repo"))[0].Content
	driverSrc := "const calls = []\n" +
		"globalThis.phase = () => {}\n" +
		"globalThis.log = () => {}\n" +
		"globalThis.parallel = async (thunks) => Promise.all(thunks.map((fn) => fn()))\n" +
		"globalThis.agent = async (prompt, opts) => {\n" +
		"  const label = (opts && opts.label) || ''\n" +
		"  calls.push({ label, prompt })\n" +
		"  " + agentBody + "\n" +
		"}\n" +
		harnessEvalForm(content) +
		"\nawait __wf__({ task: 'T1' })\n" +
		"const gate = calls.find((c) => c.label === 'gate:T1')\n" +
		"process.stdout.write(JSON.stringify({ labels: calls.map((c) => c.label), gatePrompt: gate ? gate.prompt : '' }))\n"
	driver := filepath.Join(dir, "gating.mjs")
	if err := os.WriteFile(driver, []byte(driverSrc), 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command(node, driver).CombinedOutput()
	if err != nil {
		t.Fatalf("mock runner failed: %v\n%s", err, out)
	}
	var res ccMockResult
	if err := json.Unmarshal(out, &res); err != nil {
		t.Fatalf("mock runner output does not parse: %v\n%s", err, out)
	}
	return res
}

