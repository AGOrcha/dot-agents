// TestCCEmitNoRoutineNoCrossFamily exercises the manifest branches where the
// routine lens group and/or the cross-family gate are absent: empty slices must
// render as `[]` and an absent cross-family as `null`.
func TestCCEmitNoRoutineNoCrossFamily(t *testing.T) {
	exec := StageRoute{Slug: "default", Model: "claude-opus-4-8", ModelFamily: "claude"}
	spec := PipelineSpec{
		Workspace:   "/repo",
		AppType:     "bare",
		TargetCount: 3,
		Executor:    exec,
		Verifiers:   []StageRoute{exec, exec},
	}
	content := emitCC(t, spec)[0].Content
	if !strings.Contains(content, "\"routineLenses\": []") {
		t.Fatal("empty routine lenses must render as []")
	}
	if !strings.Contains(content, "\"crossFamily\": null") {
		t.Fatal("absent cross-family must render as null")
	}
	m := parseCCManifest(t, content)
	if len(m.RoutineLenses) != 0 || m.CrossFamily != nil {
		t.Fatalf("manifest routine/cross = %+v / %+v", m.RoutineLenses, m.CrossFamily)
	}

	// Cross-family present but no routine lenses.
	cross := StageRoute{Slug: crossFamilyLensSlug, Model: "gpt-5.4", ModelFamily: "gpt"}
	spec.CrossFamily = &cross
	m2 := parseCCManifest(t, emitCC(t, spec)[0].Content)
	if m2.CrossFamily == nil || m2.CrossFamily.Slug != crossFamilyLensSlug {
		t.Fatalf("cross-family = %+v", m2.CrossFamily)
	}
}

// TestCCStableRunnerRegionIdentical proves the generated-vs-authored boundary:
// the STABLE RUNNER region (banner → EOF) is byte-identical across an unrelated
// skeleton and a specialized emit — only the header digest and MANIFEST differ.
func TestCCStableRunnerRegionIdentical(t *testing.T) {
	skeleton := emitCC(t, skeletonSpec("/repo"))
	spec, err := BuildPipelineSpec("/repo", "go-cli", fixtureStageProfiles(), fixtureExecProfile())
	if err != nil {
		t.Fatal(err)
	}
	special := emitCC(t, spec)

	runnerTail := func(content string) string {
		i := strings.Index(content, ccStableRunnerMarker)
		if i < 0 {
			t.Fatal("no stable runner marker")
		}
		return content[i:]
	}
	if runnerTail(skeleton[0].Content) != runnerTail(special[0].Content) {
		t.Fatal("pipeline stable runner region drifted between profiles")
	}
	if runnerTail(skeleton[1].Content) != runnerTail(special[1].Content) {
		t.Fatal("reconcile stable runner region drifted between profiles")
	}
}

