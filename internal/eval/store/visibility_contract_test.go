package store_test

import (
	"math"
	"os"
	"path/filepath"
	"testing"

	"github.com/AGOrcha/dot-agents/internal/eval"
	"github.com/AGOrcha/dot-agents/internal/eval/store"
	"github.com/AGOrcha/dot-agents/internal/scoring"
	"go.yaml.in/yaml/v3"
)

// visibility_contract_test.go pins the on-disk contract the R2 dashboard
// consumes (documented in docs/EVAL_HARNESS.md → "R2 visibility contract"). It
// loads the FROZEN fixture run under testdata/ and asserts that (1) each of the
// four sidecar files still deserializes into its real production type and (2)
// the documented JOIN keys resolve consistently across the files. It is the
// verification that the layout stays a stable contract R2 can build against
// without re-running the harness.

// Frozen fixture identity + join-key values. The fixture was generated by the
// real store / scoring / scoringbridge / taskspec pipeline; these consts are
// the join keys the contract documents.
const (
	contractRunID    = "r2contract-go-impl-pure-fn"
	contractTaskID   = "go-impl-pure-fn-001"
	contractTemplate = "impl-pure-fn"
	contractLanguage = "go"
	contractDiff     = "medium"

	evalRunFileName   = "eval-run.yaml"
	taskspecFileName  = "taskspec.yaml"
	iterRecordName    = "iter-1.yaml"
	iterScoreName     = "iter-1.score.yaml"
	iterLogDirName    = "iteration-log"
	testdataDirName   = "testdata"
	scoreValueEpsilon = 1e-9
)

// contractFixtureDir is the frozen fixture run directory
// (testdata/<run-id>). Go excludes testdata/ from the build, so the fixture is
// inert data addressed by this relative path from the package directory.
func contractFixtureDir() string {
	return filepath.Join(testdataDirName, contractRunID)
}

// readContractFile reads one fixture sidecar and fails the test if it is
// missing — a missing file is itself a contract regression.
func readContractFile(t *testing.T, parts ...string) []byte {
	t.Helper()
	path := filepath.Join(parts...)
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read fixture %s: %v", path, err)
	}
	return data
}

// loadPersistedEvalRun deserializes eval-run.yaml into the real store type.
func loadPersistedEvalRun(t *testing.T) store.PersistedEvalRun {
	t.Helper()
	var p store.PersistedEvalRun
	if err := yaml.Unmarshal(readContractFile(t, contractFixtureDir(), evalRunFileName), &p); err != nil {
		t.Fatalf("unmarshal %s into store.PersistedEvalRun: %v", evalRunFileName, err)
	}
	return p
}

// loadPersistedScore deserializes iter-1.score.yaml into the real scoring type.
func loadPersistedScore(t *testing.T) scoring.PersistedScore {
	t.Helper()
	var s scoring.PersistedScore
	if err := yaml.Unmarshal(readContractFile(t, contractFixtureDir(), iterLogDirName, iterScoreName), &s); err != nil {
		t.Fatalf("unmarshal %s into scoring.PersistedScore: %v", iterScoreName, err)
	}
	return s
}

// TestVisibilityContract_ArtifactsDeserialize asserts every fixture file still
// parses into its production type via the real loaders — the R2 dashboard reads
// exactly these types.
func TestVisibilityContract_ArtifactsDeserialize(t *testing.T) {
	// taskspec.yaml → eval.TaskSpec (strict decode + validation).
	spec, err := eval.ParseTaskSpec(readContractFile(t, contractFixtureDir(), taskspecFileName))
	if err != nil {
		t.Fatalf("ParseTaskSpec(%s) = %v, want nil", taskspecFileName, err)
	}
	if spec.TaskID != contractTaskID {
		t.Errorf("taskspec task_id = %q, want %q", spec.TaskID, contractTaskID)
	}

	// eval-run.yaml → store.PersistedEvalRun.
	run := loadPersistedEvalRun(t)
	if run.RunID != contractRunID {
		t.Errorf("eval-run run_id = %q, want %q", run.RunID, contractRunID)
	}

	// iter-1.score.yaml → scoring.PersistedScore with a populated breakdown.
	score := loadPersistedScore(t)
	if !score.Scored || len(score.Breakdown) == 0 {
		t.Errorf("iter-1.score.yaml scored=%v breakdown-rows=%d, want scored with a non-empty breakdown", score.Scored, len(score.Breakdown))
	}

	// iter-1.yaml → scoring.IterationRecord (the R1-shaped iteration entry).
	rec, err := scoring.ParseIterationRecord(readContractFile(t, contractFixtureDir(), iterLogDirName, iterRecordName))
	if err != nil {
		t.Fatalf("ParseIterationRecord(%s) = %v, want nil", iterRecordName, err)
	}
	if rec.Iteration != score.Iteration {
		t.Errorf("iter record iteration = %d, score iteration = %d, want equal", rec.Iteration, score.Iteration)
	}
}

// TestVisibilityContract_JoinKeysResolve asserts the documented JOIN keys
// resolve consistently across the four files: the run-identity join
// (run_id == wave == dir name), the task-metadata join (task_id ties eval-run
// ↔ taskspec ↔ iter record; language / difficulty match), the prompt-id
// provenance (taskspec.generated_from.template_id, integrity-pinned by
// agent.prompt_digest == sha256(taskspec.prompt)), and the score-summary join
// (eval-run.score mirrors iter-1.score.yaml).
func TestVisibilityContract_JoinKeysResolve(t *testing.T) {
	spec, err := eval.ParseTaskSpec(readContractFile(t, contractFixtureDir(), taskspecFileName))
	if err != nil {
		t.Fatalf("ParseTaskSpec(%s) = %v, want nil", taskspecFileName, err)
	}
	run := loadPersistedEvalRun(t)
	score := loadPersistedScore(t)
	rec, err := scoring.ParseIterationRecord(readContractFile(t, contractFixtureDir(), iterLogDirName, iterRecordName))
	if err != nil {
		t.Fatalf("ParseIterationRecord(%s) = %v, want nil", iterRecordName, err)
	}

	// Run-identity join: eval-run.run_id == iter-1.yaml wave == the dir name.
	if run.RunID != contractRunID {
		t.Errorf("eval-run run_id = %q, want %q", run.RunID, contractRunID)
	}
	if rec.Wave != run.RunID {
		t.Errorf("iter-1.yaml wave = %q, want run_id %q", rec.Wave, run.RunID)
	}

	// Task-metadata join: task_id ties the three files together.
	if run.TaskID != contractTaskID || spec.TaskID != contractTaskID || rec.TaskID != contractTaskID {
		t.Errorf("task_id mismatch: eval-run=%q taskspec=%q iter-record=%q, want %q",
			run.TaskID, spec.TaskID, rec.TaskID, contractTaskID)
	}

	// language / difficulty are denormalized onto eval-run.yaml for list
	// rendering; taskspec.yaml is canonical. Both must agree.
	if run.Language != contractLanguage || string(spec.Language) != contractLanguage {
		t.Errorf("language: eval-run=%q taskspec=%q, want %q", run.Language, spec.Language, contractLanguage)
	}
	if run.Difficulty != contractDiff || string(spec.Difficulty) != contractDiff {
		t.Errorf("difficulty: eval-run=%q taskspec=%q, want %q", run.Difficulty, spec.Difficulty, contractDiff)
	}

	// prompt-id provenance: the human-readable prompt identity is the template
	// id on taskspec.yaml; its integrity is pinned by the eval-run prompt
	// digest over the exact prompt bytes.
	if spec.GeneratedFrom.TemplateID != contractTemplate {
		t.Errorf("taskspec generated_from.template_id = %q, want %q", spec.GeneratedFrom.TemplateID, contractTemplate)
	}
	if got := wantDigest(spec.Prompt); run.Agent.PromptDigest != got {
		t.Errorf("agent.prompt_digest = %q, want sha256(taskspec.prompt) = %q", run.Agent.PromptDigest, got)
	}

	// Score-summary join: eval-run.score is a summary of iter-1.score.yaml.
	if math.Abs(run.Score.Value-score.Value) > scoreValueEpsilon {
		t.Errorf("score value: eval-run=%v iter-score=%v, want equal", run.Score.Value, score.Value)
	}
	if run.Score.Band != score.Band {
		t.Errorf("score band: eval-run=%q iter-score=%q, want equal", run.Score.Band, score.Band)
	}
	if run.Score.Scored != score.Scored {
		t.Errorf("score scored: eval-run=%v iter-score=%v, want equal", run.Score.Scored, score.Scored)
	}
	if run.Score.RubricVersion != score.RubricVersion || run.Score.RubricVersion == "" {
		t.Errorf("rubric_version: eval-run=%q iter-score=%q, want equal and non-empty",
			run.Score.RubricVersion, score.RubricVersion)
	}
}
