// withPipelineFixture chdirs into a fresh temp repo and stubs appTypeSnapshot to
// the fixture config, restoring both on cleanup.
func withPipelineFixture(t *testing.T, snap func(string) (*config.Snapshot, error)) string {
	t.Helper()
	repo := t.TempDir()
	oldwd, _ := os.Getwd()
	t.Cleanup(func() { _ = os.Chdir(oldwd) })
	if err := os.Chdir(repo); err != nil {
		t.Fatal(err)
	}
	orig := appTypeSnapshot
	t.Cleanup(func() { appTypeSnapshot = orig })
	appTypeSnapshot = snap
	return repo
}

func runPipelineEmit(t *testing.T, jsonOut bool, args ...string) (string, error) {
	t.Helper()
	prev := workflowTestJSON
	workflowTestJSON = jsonOut
	t.Cleanup(func() { workflowTestJSON = prev })
	cmd := newWorkflowPipelineEmitCmd()
	var buf bytes.Buffer
	cmd.SetOut(&buf)
	cmd.SetErr(&buf)
	cmd.SetArgs(args)
	err := cmd.Execute()
	return buf.String(), err
}

func TestPipelineEmitWritesSkeleton(t *testing.T) {
	repo := withPipelineFixture(t, func(string) (*config.Snapshot, error) { return pipelineFixtureSnapshot(), nil })
	out, err := runPipelineEmit(t, false, "--platform", "omp")
	if err != nil {
		t.Fatalf("emit: %v", err)
	}
	if !strings.Contains(out, "wrote") {
		t.Fatalf("output missing wrote line:\n%s", out)
	}
	inner := filepath.Join(repo, ".agents", "workflow", "runtime", "full-loop", "profile-driven.swarm.yaml")
	data, err := os.ReadFile(inner)
	if err != nil {
		t.Fatalf("emitted inner YAML missing: %v", err)
	}
	if !strings.HasPrefix(string(data), "# generated by da workflow pipeline emit; do not hand-edit\n") {
		t.Fatalf("emitted YAML missing generation header:\n%s", string(data)[:80])
	}
	if _, err := os.Stat(filepath.Join(repo, ".agents", "workflow", "runtime", "full-loop", "reconcile.swarm.yaml")); err != nil {
		t.Fatalf("emitted reconcile YAML missing: %v", err)
	}
}

func TestPipelineEmitSpecialized(t *testing.T) {
	repo := withPipelineFixture(t, func(string) (*config.Snapshot, error) { return pipelineFixtureSnapshot(), nil })
	if _, err := runPipelineEmit(t, false, "--platform", "omp", "--app-type", "go-cli"); err != nil {
		t.Fatalf("emit go-cli: %v", err)
	}
	dir := filepath.Join(repo, ".agents", "workflow", "runtime", "full-loop")
	if _, err := os.Stat(filepath.Join(dir, "profile-driven.go-cli.swarm.yaml")); err != nil {
		t.Fatalf("specialized inner YAML missing: %v", err)
	}
	// The canonical skeleton file must NOT be clobbered by a specialized emit.
	if _, err := os.Stat(filepath.Join(dir, "profile-driven.swarm.yaml")); !os.IsNotExist(err) {
		t.Fatalf("specialized emit should not write the canonical skeleton file (err=%v)", err)
	}
}

