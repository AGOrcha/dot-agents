func TestPipelineEmitJSON(t *testing.T) {
	withPipelineFixture(t, func(string) (*config.Snapshot, error) { return pipelineFixtureSnapshot(), nil })
	out, err := runPipelineEmit(t, true, "--platform", "omp", "--dry-run")
	if err != nil {
		t.Fatalf("json emit: %v", err)
	}
	var res pipelineEmitResult
	if err := json.Unmarshal([]byte(out), &res); err != nil {
		t.Fatalf("json output does not parse: %v\n%s", err, out)
	}
	if res.Platform != "omp" || !res.DryRun || res.Digest == "" || len(res.Artifacts) != 2 {
		t.Fatalf("unexpected json result: %+v", res)
	}
	if res.Artifacts[0].Bytes == 0 {
		t.Fatalf("artifact bytes should be non-zero: %+v", res.Artifacts[0])
	}
}

